-- Part Manager schema for PostgreSQL / Supabase.
--
-- Mirrors the SQLite schema in database.py column for column, so data can be
-- copied both ways (scripts/migrate_sqlite_to_postgres.py, flask backup-db).
-- Safe to run repeatedly: every statement is IF NOT EXISTS / idempotent.
--
-- Apply with `flask --app app init-db` (DATABASE_URL set), or paste this file
-- into the Supabase SQL editor.
--
-- Timestamps stay TEXT in ISO-8601 UTC form ("2026-10-13T15:12:11Z"), exactly
-- as the app writes and displays them; they are never parsed as dates.

CREATE TABLE IF NOT EXISTS admin (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             TEXT    NOT NULL CHECK (length(trim(username)) BETWEEN 1 AND 50),
    password_hash        TEXT    NOT NULL,
    must_change_password INTEGER NOT NULL DEFAULT 0 CHECK (must_change_password IN (0, 1)),
    created_at           TEXT    NOT NULL
);
-- SQLite used UNIQUE COLLATE NOCASE; this is the case-insensitive equivalent.
CREATE UNIQUE INDEX IF NOT EXISTS admin_username_lower_key ON admin (lower(username));

CREATE TABLE IF NOT EXISTS parts (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_name      TEXT    NOT NULL CHECK (length(trim(part_name)) BETWEEN 1 AND 120),
    part_number    TEXT    NOT NULL CHECK (length(trim(part_number)) BETWEEN 1 AND 80),
    line_storage   TEXT    NOT NULL CHECK (length(trim(line_storage)) BETWEEN 1 AND 120),
    ols_storage    TEXT    NOT NULL CHECK (length(trim(ols_storage)) BETWEEN 1 AND 120),
    image_filename TEXT,
    trolley_qty    INTEGER CHECK (trolley_qty IS NULL OR trolley_qty BETWEEN 1 AND 9999),
    created_at     TEXT    NOT NULL,
    updated_at     TEXT    NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_parts_name ON parts (lower(part_name));
CREATE INDEX IF NOT EXISTS idx_parts_part_number ON parts (lower(part_number));

CREATE TABLE IF NOT EXISTS sub_parts (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id        INTEGER NOT NULL REFERENCES parts (id) ON DELETE CASCADE,
    part_name      TEXT    NOT NULL CHECK (length(trim(part_name)) BETWEEN 1 AND 120),
    part_number    TEXT    NOT NULL CHECK (length(trim(part_number)) BETWEEN 1 AND 80),
    trolley_qty    INTEGER CHECK (trolley_qty IS NULL OR trolley_qty BETWEEN 1 AND 9999),
    image_filename TEXT,
    created_at     TEXT    NOT NULL,
    updated_at     TEXT    NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sub_parts_part_id ON sub_parts (part_id);

-- Login rate-limit counters shared by every serverless instance
-- (see ratelimit_pg.py). Rows expire on their own; nothing else uses them.
CREATE TABLE IF NOT EXISTS rate_limits (
    key        TEXT             PRIMARY KEY,
    count      INTEGER          NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL
);

-- Supabase publishes the public schema through its Data API to the "anon"
-- and "authenticated" roles. This app only talks to the database from the
-- server, so lock those roles out: RLS on with no policies, and no grants.
-- The connection role in DATABASE_URL owns the tables and is unaffected.
ALTER TABLE admin       ENABLE ROW LEVEL SECURITY;
ALTER TABLE parts       ENABLE ROW LEVEL SECURITY;
ALTER TABLE sub_parts   ENABLE ROW LEVEL SECURITY;
ALTER TABLE rate_limits ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE r TEXT;
BEGIN
    FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
            EXECUTE format('REVOKE ALL ON admin, parts, sub_parts, rate_limits FROM %I', r);
        END IF;
    END LOOP;
END
$$;
